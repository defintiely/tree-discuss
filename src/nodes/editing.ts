import { create } from 'zustand';
import type { NodeId } from '../types';

/**
 * Какой узел сейчас правится. Пока правка идёт, канвас рисует все узлы, а не
 * только видимые: большая вставка резко удлиняет узел, камера едет за кареткой
 * вниз, а React Flow ещё помнит старую высоту — счёл бы узел ушедшим за кадр
 * и выкинул его из DOM вместе с полем правки и всем набранным.
 */
export const useEditing = create<{ id: NodeId | null }>(() => ({ id: null }));
